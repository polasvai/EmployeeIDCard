#!/usr/bin/env node
import fs from 'fs';
import path from 'path';
import { execSync } from 'child_process';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');

function run(cmd, desc) {
  console.log(`\n\x1b[36m▶ ${desc || cmd}\x1b[0m`);
  execSync(cmd, { cwd: rootDir, stdio: 'inherit' });
}

try {
  console.log('\n\x1b[35m===========================================');
  console.log('   ID Card Studio - Auto-Version Publisher');
  console.log('===========================================\x1b[0m\n');

  // 1. Read package.json
  const pkgPath = path.join(rootDir, 'package.json');
  const pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf8'));
  const currentVersion = pkg.version || '2.0.0';

  // 2. Increment patch version (e.g. 2.0.0 -> 2.0.1)
  const parts = currentVersion.split('.').map((p) => parseInt(p, 10) || 0);
  while (parts.length < 3) parts.push(0);
  parts[2] += 1;
  const newVersion = parts.join('.');

  console.log(`\x1b[32m✔ Version Bump: v${currentVersion} ➔ v${newVersion}\x1b[0m`);

  // 3. Write package.json
  pkg.version = newVersion;
  fs.writeFileSync(pkgPath, JSON.stringify(pkg, null, 2) + '\n', 'utf8');

  // 4. Update src/config/version.js
  const versionJsPath = path.join(rootDir, 'src', 'config', 'version.js');
  const today = new Date().toISOString().split('T')[0];
  const versionJsContent = `// Auto-generated by scripts/publish.mjs
export const APP_VERSION = '${newVersion}';
export const RELEASE_DATE = '${today}';
`;
  fs.writeFileSync(versionJsPath, versionJsContent, 'utf8');

  // 5. Run build
  run('npm run build', `Building production bundle for v${newVersion}`);

  // 6. Git commit & push
  const customMessage = process.argv.slice(2).join(' ').trim();
  const commitMsg = customMessage
    ? `chore(release): v${newVersion} - ${customMessage}`
    : `chore(release): bump version to v${newVersion}`;

  run('git add .', 'Staging updated files');
  try {
    run(`git commit -m "${commitMsg.replace(/"/g, '\\"')}"`, 'Committing release');
  } catch (err) {
    console.log('\x1b[33mNo additional git changes to commit.\x1b[0m');
  }
  run('git push origin main', 'Pushing release to GitHub main');

  // 7. Deploy to Cloudflare Workers with Wrangler
  run('npx wrangler deploy', 'Deploying static assets and worker to Cloudflare edge');

  console.log('\n\x1b[32m=======================================================');
  console.log(`🎉 Successfully published v${newVersion} to https://employee.idcard.bd`);
  console.log('=======================================================\x1b[0m\n');
} catch (error) {
  console.error('\n\x1b[31m✖ Deployment failed:\x1b[0m', error.message);
  process.exit(1);
}
